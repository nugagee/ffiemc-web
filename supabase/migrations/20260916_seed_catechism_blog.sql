<h3>What is a catechism?</h3>
<p>A catechism is not a replacement for the Bible. It is a <strong>faithful snapshot of the Bible's teaching</strong> — short questions, clear answers — so that doctrine can be remembered, discussed, and lived. It is the classroom of the church: pastors, parents, youth executives, and every disciple learning together.</p>
<p>If doctrine is the backbone of the believer, the catechism is the <strong>daily exercise</strong> that keeps that backbone strong.</p>

<h3>A snapshot from our About page</h3>
<p>Here are the questions we teach at Fire-Fire International Evangelical Church. Read them slowly. Share one with your fellowship this week. Then go deeper on the full Catechism section of our website.</p>
<ol>
<li><strong>How do we know that God exists?</strong> — We know God exists through understanding the Bible and observing the order and design of the world He created.</li>
<li><strong>What do we believe about the Trinity?</strong> — We believe in one God revealed as God the Father, God the Son, and God the Holy Spirit — the Godhead in three Persons.</li>
<li><strong>What is the nature of man?</strong> — Man is God's creation, made with the ability to think, choose, and relate to his Creator.</li>
<li><strong>How did man fall into sin?</strong> — Man fell into slavery and hardship through sin, departing from God's command and losing fellowship with Him.</li>
<li><strong>What is the means of salvation?</strong> — Salvation is by grace through faith in Jesus Christ, not by human merit or works.</li>
<li><strong>Who is Jesus Christ?</strong> — Jesus Christ is the Son of God and the Saviour of the world.</li>
<li><strong>Who is the Holy Spirit?</strong> — The Holy Spirit is the third Person of the Trinity, equal with the Father and the Son.</li>
<li><strong>What is the work of the Holy Spirit?</strong> — The Holy Spirit guides, teaches, comforts, convicts of sin, sanctifies, and empowers believers for holy living and service.</li>
<li><strong>What is sin?</strong> — Sin is the violation of God's commandment — transgression of His holy law.</li>
<li><strong>What is the wages of sin?</strong> — The wages of sin is death — spiritual separation from God and eternal judgment.</li>
<li><strong>How can we be saved from sin?</strong> — Salvation from sin is only through Jesus Christ, who died and rose again for us.</li>
<li><strong>What is heaven?</strong> — Heaven is the place and state of blessing — the eternal habitation of God and His redeemed people.</li>
<li><strong>What is hell?</strong> — Hell is the place of suffering — the habitation of the devil, sin, and eternal death for the unredeemed.</li>
<li><strong>What is faith?</strong> — Faith is the substance of things hoped for, the evidence of things not seen (Hebrews 11:1).</li>
<li><strong>What is the Bible?</strong> — The Bible is the holy Word of God — inspired, infallible, and our final authority for faith and life.</li>
<li><strong>What did Jesus say about children?</strong> — Suffer little children to come unto Me… for of such is the kingdom of heaven (Matthew 19:14).</li>
<li><strong>Can we fully understand God?</strong> — There are things about God we cannot fully comprehend; we humbly trust what He has revealed in Scripture.</li>
<li><strong>How should a Christian treat others?</strong> — See God in others, pray for understanding of His Word, and walk humbly in love and holiness.</li>
<li><strong>What do we believe about the resurrection?</strong> — We believe in the resurrection of the dead — to eternal life for the saved and eternal damnation for the lost, according to God's promise and power.</li>
<li><strong>Who fell into sin first?</strong> — Eve was the first to fall into sin after being deceived by the serpent; Adam also transgressed, and sin entered the human race.</li>
<li><strong>What must we do to receive forgiveness?</strong> — Repent, confess our sins to God, believe in Jesus Christ, and forsake sin with a willing heart.</li>
<li><strong>What lesson do we learn from Peter's denial?</strong> — Even when we fail, God restores the repentant heart. Failure is not final when we return to Christ.</li>
