<li><strong>Name the twelve tribes of Israel.</strong> — Reuben, Simeon, Levi, Judah, Dan, Naphtali, Gad, Asher, Issachar, Zebulun, Joseph, and Benjamin.</li>
<li><strong>Why is medicine often bitter?</strong> — The word of God may seem bitter to the carnal mind, but it heals the soul as medicine heals the body.</li>
<li><strong>What does rain from the sea teach us?</strong> — As clouds draw from the sea and return rain, ministers receive from God and pass knowledge to others.</li>
<li><strong>What does the rainbow signify?</strong> — The rainbow is the covenant sign of God's grace and faithfulness to His people.</li>
