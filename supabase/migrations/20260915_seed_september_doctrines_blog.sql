<p>Happy New Month, beloved family! 🙏</p>
<p>As we step into <strong>September</strong>, we thank God for His faithfulness through every season. A new month is more than a calendar change — it is a fresh invitation to <strong>return to the foundation</strong> of what we believe, why we gather, and what Fire-Fire International Evangelical Church stands for in Christ.</p>
<p>Whether you worship at Headquarters, an assembly across Ibadan, or a campus fellowship — we are one family united by <strong>sound doctrine</strong> and a passion to <em>teach one by one another</em>.</p>
<h3>Why doctrine matters</h3>
<p>Doctrine is the backbone of the believer. It is what foundation is to a building — for solidity, stability, security, strength and substance.</p>
<p>We are called to <strong>possess, pursue, practice, proclaim, preserve, and preach</strong> the truth — passing it faithfully to the next generation (Proverbs 30:5–6; Deuteronomy 6:6–7).</p>
<p>Doctrine is not dry religion. It is the <strong>backbone of the believer</strong> — the solid ground beneath every prayer, every service, and every step of faith.</p>
<h3>A snapshot: what we believe</h3>
<p>Below is a brief overview of our <strong>30 foundational doctrines</strong>. Each one is rooted in Scripture and explained in full on our About page.</p>
<ol>
<li><strong>1. The Holy Bible</strong> — The Holy Bible contains 39 books in the Old Testament and 27 in the New Testament. It is the inspiration of God and the final authority for Christians — a light that guides, spiritual food, salvation, a shield, and a manual for living.</li>
<li><strong>2. The Godhead</strong> — The Bible teaches that the Trinity is the revelation and manifestation of God Himself — God the Father, God the Son, and God the Holy Spirit. He is the Creator who reveals Himself to sinners and restores fellowship through Christ.</li>
<li><strong>3. The Virgin Birth of Jesus</strong> — Jesus was born of God without human chromosomes or the trait and genes of Adam. He was conceived by the Holy Spirit to save mankind from sin.</li>
<li><strong>4. The Sinfulness of All Men</strong> — All men are born sinners through the fall of Adam and Eve and are worthy of God's wrath apart from Christ.</li>
<li><strong>5. Repentance</strong> — Genuine repentance comes through faith: admit you are a sinner, identify your sins, confess them, forsake the pleasure of sin and the world, and be ready for restitution.</li>
<li><strong>6. Faith in Christ</strong> — Faith is giving your life to Jesus and relying on Him — believing His birth, name, words, sufferings, blood, death, Spirit, resurrection, and ascension.</li>
<li><strong>7. Restitution</strong> — Restitution is the amendment of wrongdoings — returning stolen goods, confessing sins to victims, and seeking forgiveness to maintain a good conscience before God and man.</li>
<li><strong>8. Justification</strong> — Justification is the saving grace of God for sinners who rely entirely on Christ — sins removed and the believer regarded as righteous before God.</li>
<li><strong>9. Water Baptism</strong> — A cardinal teaching following repentance and faith. The believer is immersed once in the name of the Father, Son, and Holy Spirit — dead to sin and alive to God.</li>
<li><strong>10. The Lord's Supper</strong> — Instituted by Jesus to remember His death until He returns, using unleavened bread and the fruit of the vine as symbols of His body and blood.</li>
<li><strong>11. Entire Sanctification</strong> — A gracious work of God in the saved whereby adamic and generational natures are removed, producing godliness, holiness, and peace.</li>
<li><strong>12. Prayer</strong> — Prayer is communion with God and spiritual warfare against Satan. Its ingredients include faith, fasting, zeal, and charity.</li>
<li><strong>13. Fasting</strong> — Abstinence from food and drink to humble the soul and seek the Holy Spirit — including three-day, seven-day, and extended fasts.</li>
<li><strong>14. Holy Ghost Baptism</strong> — Divine empowerment for service, often evidenced by speaking in new tongues and bold witness for Christ.</li>
<li><strong>15. Fruits of the Spirit</strong> — Love, joy, peace, longsuffering, kindness, goodness, faithfulness, gentleness, and self-control — the evidence of abiding in Christ.</li>
<li><strong>16. Gifts of the Spirit</strong> — Speaking in tongues, prophecy, wisdom, knowledge, discernment, miracles, and healing — to be exercised in holiness, not for show.</li>
<li><strong>17. Signs, Wonders and Miracles</strong> — God still works wonders as testimony to His promise, yet the saving word of God remains most essential.</li>
<li><strong>18. Redemption from Curse, Healing and Health</strong> — Health and wholeness are provided through the suffering and blood of Jesus Christ our Healer.</li>
<li><strong>19. Evangelism</strong> — God's commission for every believer to bring others to Christ through witness and discipleship.</li>
<li><strong>20. The Christian Family</strong> — The family is God's union of a man and woman. The man leads in love; the woman supports; children are nurtured in the fear of the Lord.</li>
<li><strong>21. Marriage</strong> — An institution between a mature man and woman — monogamous and lifelong. New Testament teaching does not permit divorce while a spouse lives.</li>
<li><strong>22. The Church of God</strong> — The model of the heavenly church — an embassy for repentant believers and a place of spiritual nourishment, teaching, and care.</li>
<li><strong>23. Christian Ceremonies</strong> — Ceremonies should glorify God, not fund-raise or lead to debt. Members celebrate with gratitude; invites assist and give as led.</li>
<li><strong>24. Charity</strong> — Good measure, pressed down — tithes, offerings to the poor, and willing gifts to God and His work.</li>
<li><strong>25. The Will of God</strong> — Seek what is acceptable to God and walk in the wisdom of His will, as David and Paul exemplified.</li>
<li><strong>26. Doing Things in the Right Way</strong> — There is a God-appointed time and pattern for everything. Obedience to biblical order honours the Lord.</li>
<li><strong>27. The Christian's Cross</strong> — Self-denial and daily following of Christ — if any man will follow Me, let him deny himself and take up his cross.</li>
<li><strong>28. The Rapture</strong> — The catching away of saints — the first major eschatological event separating the redeemed from the world.</li>
<li><strong>29. Resurrection of the Dead</strong> — All souls shall rise: Christ first, then Old Testament saints, tribulation saints, and New Testament saints.</li>
<li><strong>30. Christ's Throne of Judgment (Bema)</strong> — The judgment of the redeemed after the Rapture for rewards according to works — not for sin, but for eternal profit.</li>
</ol>
